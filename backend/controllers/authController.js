exports.updateProfile = async (req, res) => {
  try {
    const { name, email, phone, profilePicture } = req.body;
    const updateData = {};
    if (name !== undefined) updateData.name = name;
    if (phone !== undefined) updateData.phone = phone;
    if (profilePicture !== undefined) updateData.profilePicture = profilePicture;

    const normalizedEmail = email ? email.toLowerCase().trim() : undefined;
    if (normalizedEmail !== undefined) updateData.email = normalizedEmail;

    // Check if email already in use
    if (normalizedEmail && normalizedEmail !== req.user.email) {
      const emailExists = await prisma.user.findUnique({ where: { email: normalizedEmail } });
      if (emailExists) {
        return res.status(400).json({ success: false, message: 'An account with this email already exists.' });
      }
    }

    if (hasSupabaseKeys) {
      // Sync email/metadata to Supabase if it changed
      const supabaseUpdates = {};
      if (normalizedEmail && normalizedEmail !== req.user.email) supabaseUpdates.email = normalizedEmail;
      if (name) supabaseUpdates.data = { name };
      
      if (Object.keys(supabaseUpdates).length > 0) {
        const { error } = await supabase.auth.admin.updateUserById(req.user.id, supabaseUpdates);
        if (error) {
          return res.status(400).json({ success: false, message: `Supabase update failed: ${error.message}` });
        }
      }
    }

    const updatedUser = await prisma.user.update({
      where: { id: req.user.id },
      data: updateData
    });
    
    updatedUser.password = undefined;
    res.status(200).json({ success: true, data: updatedUser });
  } catch (err) {
    res.status(400).json({ success: false, message: err.message });
  }
};

exports.updatePassword = async (req, res) => {
  try {
    const { currentPassword, newPassword } = req.body;
    if (!currentPassword || !newPassword) {
      return res.status(400).json({ success: false, message: 'Please provide current and new passwords.' });
    }

    const passCheck = validatePasswordStrength(newPassword);
    if (!passCheck.valid) {
      return res.status(400).json({ success: false, message: passCheck.message });
    }

    const user = await prisma.user.findUnique({ where: { id: req.user.id } });

    if (hasSupabaseKeys) {
      // Update password in Supabase Auth
      const { error } = await supabase.auth.updateUser({ password: newPassword });
      if (error) {
        return res.status(400).json({ success: false, message: `Supabase password update failed: ${error.message}` });
      }
    }

    // Local password update (with comparison verify if local password was stored)
    if (user.password) {
      const isMatch = await bcrypt.compare(currentPassword, user.password);
      if (!isMatch) {
        return res.status(400).json({ success: false, message: 'Incorrect current password.' });
      }
    }

    const salt = await bcrypt.genSalt(10);
    const hashedPassword = await bcrypt.hash(newPassword, salt);

    await prisma.user.update({
      where: { id: req.user.id },
      data: { password: hashedPassword }
    });

    res.status(200).json({ success: true, message: 'Password updated successfully.' });
  } catch (err) {
    res.status(400).json({ success: false, message: err.message });
  }
};

