exports.updateBankAccount = async (req, res) => {
  try {
    const { bankAccountName, bankAccountNumber, bankIfsc, bankName, bankBranch, bankAccountVerified } = req.body;

    if (!bankAccountName || !bankAccountNumber || !bankIfsc) {
      return res.status(400).json({ success: false, message: 'Please provide Account Holder Name, Account Number, and IFSC.' });
    }

    // Validate Account Holder Name
    const nameTrimmed = bankAccountName.trim();
    if (nameTrimmed.length < 3) {
      return res.status(400).json({ success: false, message: 'Account Holder Name must be at least 3 characters.' });
    }
    if (/[0-9]/.test(nameTrimmed)) {
      return res.status(400).json({ success: false, message: 'Account Holder Name cannot contain numbers.' });
    }

    // Validate Account Number digits (9-18 digits)
    const accNum = bankAccountNumber.trim();
    if (!/^\d{9,18}$/.test(accNum)) {
      return res.status(400).json({ success: false, message: 'Bank Account Number must be between 9 and 18 digits.' });
    }

    // Block fake/dummy account numbers (like all same digits, or sequential)
    if (/^(\d)\1+$/.test(accNum)) {
      return res.status(400).json({ success: false, message: 'Invalid Account Number. Dummy accounts with identical numbers are not allowed.' });
    }
    if (['123456789', '1234567890', '0123456789', '987654321', '9876543210'].some(seq => accNum.includes(seq))) {
      return res.status(400).json({ success: false, message: 'Invalid Account Number. Sequential dummy numbers are not allowed.' });
    }

    // Validate IFSC format: 4 letters, 0, 6 characters (digits or letters)
    const ifsc = bankIfsc.trim().toUpperCase();
    if (!/^[A-Z]{4}0[A-Z0-9]{6}$/.test(ifsc)) {
      return res.status(400).json({ success: false, message: 'Invalid IFSC code format.' });
    }

    const updatedUser = await prisma.user.update({
      where: { id: req.user.id },
      data: {
        bankAccountName: nameTrimmed,
        bankAccountNumber: accNum,
        bankIfsc: ifsc,
        bankName: bankName ? bankName.trim() : null,
        bankBranch: bankBranch ? bankBranch.trim() : null,
        bankAccountVerified: !!bankAccountVerified
      }
    });

    res.status(200).json({
      success: true,
      message: 'Bank account settings updated successfully.',
      data: {
        bankAccountName: updatedUser.bankAccountName,
        bankAccountNumber: updatedUser.bankAccountNumber,
        bankIfsc: updatedUser.bankIfsc,
        bankName: updatedUser.bankName,
        bankBranch: updatedUser.bankBranch,
        bankAccountVerified: updatedUser.bankAccountVerified
      }
    });
  } catch (err) {
    res.status(400).json({ success: false, message: err.message });
  }
};

