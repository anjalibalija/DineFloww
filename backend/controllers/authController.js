const prisma = require('../prisma/client');
const bcrypt = require('bcryptjs');
const jwt = require('jsonwebtoken');
const crypto = require('crypto');
const { supabase, hasSupabaseKeys } = require('../utils/supabase');

const VALID_ROLES = ['user', 'admin'];

const generateToken = (id, role) => {
  return jwt.sign({ id, role }, process.env.JWT_SECRET, {
    expiresIn: process.env.JWT_EXPIRE || '30d'
  });
};

const validatePasswordStrength = (password) => {
  if (password.length < 6) {
    return { valid: false, message: 'Password must be at least 6 characters.' };
  }
  if (!/[A-Z]/.test(password)) {
    return { valid: false, message: 'Password must contain at least one uppercase letter.' };
  }
  if (!/[0-9]/.test(password)) {
    return { valid: false, message: 'Password must contain at least one number.' };
  }
  if (!/[!@#$%^&*(),.?":{}|<>]/.test(password)) {
    return { valid: false, message: 'Password must contain at least one special character.' };
  }
  return { valid: true };
};

exports.signup = async (req, res) => {
  try {
    const { name, email, password, role, phone } = req.body;

    // Validate role
    const userRole = role || 'user';
    if (!VALID_ROLES.includes(userRole)) {
      return res.status(400).json({ success: false, message: 'Invalid role. Must be "user" or "admin".' });
    }

    // Normalize email or phone input
    let finalEmail = '';
    let finalPhone = '';
    let isPhoneSignup = false;

    if (email && email.includes('@')) {
      finalEmail = email.toLowerCase().trim();
      finalPhone = phone ? phone.trim() : '';
    } else if (email) {
      // Input entered in the email field was actually a phone number
      finalPhone = email.trim();
      finalEmail = `${finalPhone}@dineflow.com`;
      isPhoneSignup = true;
    } else if (phone) {
      finalPhone = phone.trim();
      finalEmail = `${finalPhone}@dineflow.com`;
      isPhoneSignup = true;
    }

    if (!name || !finalEmail || !password) {
      return res.status(400).json({ success: false, message: 'Please provide name, email or phone, and password.' });
    }

    const passCheck = validatePasswordStrength(password);
    if (!passCheck.valid) {
      return res.status(400).json({ success: false, message: passCheck.message });
    }

    // Check if user already exists
    const userExists = await prisma.user.findFirst({
      where: {
        OR: [
          { email: finalEmail },
          ...(finalPhone ? [{ phone: finalPhone }] : [])
        ]
      }
    });

    if (userExists) {
      const isEmailMatch = userExists.email === finalEmail;
      const fieldUsed = isEmailMatch ? 'email' : 'phone number';
      return res.status(400).json({ success: false, message: `An account with this ${fieldUsed} already exists.` });
    }

    const salt = await bcrypt.genSalt(10);
    const hashedPassword = await bcrypt.hash(password, salt);

    let userId;
    const verificationToken = crypto.randomBytes(32).toString('hex');

    if (hasSupabaseKeys) {
      // Create user in Supabase Auth using service client
      const { data, error } = await supabase.auth.admin.createUser({
        email: finalEmail,
        password,
        email_confirm: true,
        user_metadata: { name, role: userRole, phone: finalPhone }
      });

      if (error) {
        return res.status(400).json({ success: false, message: `Supabase registration failed: ${error.message}` });
      }

      userId = data.user.id;
    }

    const user = await prisma.user.create({
      data: {
        id: userId, // Uses Supabase ID if present, otherwise defaults to autogenerated UUID
        name,
        email: finalEmail,
        password: hashedPassword,
        role: userRole,
        phone: finalPhone,
        emailVerified: isPhoneSignup ? true : false,
        verificationToken: isPhoneSignup ? '' : verificationToken
      }
    });

    const token = generateToken(user.id, user.role);
    user.password = undefined;

    // Email verification link simulation
    let verificationLink = '';
    if (!isPhoneSignup) {
      verificationLink = `${req.protocol}://${req.get('host')}/api/auth/verify-email?token=${verificationToken}`;
      console.log(`\n📧 [EMAIL VERIFICATION LINK SENT] For ${finalEmail}: \n🔗 ${verificationLink}\n`);
    }

    res.status(201).json({ 
      success: true, 
      token, 
      user,
      _devDebug: !isPhoneSignup ? {
        verificationToken,
        verificationLink
      } : undefined
    });
  } catch (err) {
    res.status(400).json({ success: false, message: err.message });
  }
};

exports.login = async (req, res) => {
  try {
    const { email, password, role } = req.body;
    
    if (!email || !password) {
      return res.status(400).json({ success: false, message: 'Please provide email/phone and password.' });
    }

    const normalizedInput = email.toLowerCase().trim();
    let user;
    if (normalizedInput.includes('@')) {
      user = await prisma.user.findUnique({ where: { email: normalizedInput } });
    } else {
      user = await prisma.user.findFirst({
        where: {
          OR: [
            { phone: normalizedInput },
            { email: `${normalizedInput}@dineflow.com` }
          ]
        }
      });
    }

    // Check account lockout first
    if (user && user.lockUntil && user.lockUntil > new Date()) {
      const minutesLeft = Math.ceil((new Date(user.lockUntil) - new Date()) / 1000 / 60);
      return res.status(403).json({
        success: false,
        message: `This account is temporarily locked due to multiple failed login attempts. Please try again in ${minutesLeft} minute(s).`
      });
    }

    let credentialsValid = false;

    if (hasSupabaseKeys) {
      // Verify login credentials using Supabase Auth
      const { data, error } = await supabase.auth.signInWithPassword({
        email: user ? user.email : normalizedInput,
        password
      });

      if (!error) {
        credentialsValid = true;
        // Check if user exists by Supabase UUID just in case email mismatched or has different casing
        if (!user) {
          user = await prisma.user.findUnique({ where: { id: data.user.id } });
        }

        // Sync user to database table if missing
        if (!user) {
          const metadata = data.user.user_metadata || {};
          const userEmail = data.user.email || (user ? user.email : (normalizedInput.includes('@') ? normalizedInput : `${normalizedInput}@dineflow.com`));
          user = await prisma.user.create({
            data: {
              id: data.user.id,
              name: metadata.name || 'User',
              email: userEmail,
              password: '',
              role: metadata.role || 'user',
              phone: metadata.phone || (normalizedInput.includes('@') ? '' : normalizedInput),
              emailVerified: true // Supabase accounts synced can be verified by default
            }
          });
        } else {
          // If user was found but email is different/casing is different, sync email
          const targetEmail = data.user.email || user.email;
          if (user.email !== targetEmail) {
            user = await prisma.user.update({
              where: { id: user.id },
              data: { email: targetEmail }
            });
          }
        }
      }
    } else {
      // Local fallback password verification
      if (user) {
        const isMatch = await bcrypt.compare(password, user.password);
        if (isMatch) {
          credentialsValid = true;
        }
      }
    }

    if (!credentialsValid) {
      if (user) {
        // Increment failed attempts
        const attempts = user.loginAttempts + 1;
        let lockUntil = null;
        let msg = 'Invalid credentials.';

        if (attempts >= 5) {
          lockUntil = new Date(Date.now() + 15 * 60 * 1000); // 15 minutes lock
          msg = 'Account locked due to 5 failed attempts. Please try again in 15 minutes.';
        } else {
          msg = `Invalid credentials. Remaining attempts before lockout: ${5 - attempts}`;
        }

        await prisma.user.update({
          where: { id: user.id },
          data: { loginAttempts: attempts, lockUntil }
        });

        return res.status(401).json({ success: false, message: msg });
      }

      return res.status(401).json({ success: false, message: 'Invalid credentials.' });
    }

    // Validate role matches sign-in type
    if (role && user.role !== role) {
      const expected = role === 'admin' ? 'admin' : 'customer';
      return res.status(403).json({ 
        success: false, 
        message: `This account is not registered as an ${expected}. Please use the correct sign-in page.` 
      });
    }

    // 2FA check bypassed as requested by user to disable 2-step verification.

    // Normal successful login without 2FA
    await prisma.user.update({
      where: { id: user.id },
      data: { loginAttempts: 0, lockUntil: null }
    });

    const token = generateToken(user.id, user.role);
    user.password = undefined;

    res.status(200).json({ success: true, token, user });
  } catch (err) {
    res.status(400).json({ success: false, message: err.message });
  }
};

exports.verifyOtp = async (req, res) => {
  try {
    const { email, otpCode } = req.body;
    if (!email || !otpCode) {
      return res.status(400).json({ success: false, message: 'Please provide email/phone and OTP code.' });
    }

    const normalizedInput = email.toLowerCase().trim();
    let user;
    if (normalizedInput.includes('@')) {
      user = await prisma.user.findUnique({ where: { email: normalizedInput } });
    } else {
      user = await prisma.user.findFirst({
        where: {
          OR: [
            { phone: normalizedInput },
            { email: `${normalizedInput}@dineflow.com` }
          ]
        }
      });
    }

    if (!user) {
      return res.status(404).json({ success: false, message: 'User not found.' });
    }

    // Check account lockout
    if (user.lockUntil && user.lockUntil > new Date()) {
      const minutesLeft = Math.ceil((new Date(user.lockUntil) - new Date()) / 1000 / 60);
      return res.status(403).json({
        success: false,
        message: `This account is temporarily locked. Please try again in ${minutesLeft} minute(s).`
      });
    }

    if (user.otpCode !== otpCode || !user.otpExpires || user.otpExpires < new Date()) {
      // Increment failed attempts as a failed verification counts
      const attempts = user.loginAttempts + 1;
      let lockUntil = null;
      let msg = 'Invalid or expired OTP code.';

      if (attempts >= 5) {
        lockUntil = new Date(Date.now() + 15 * 60 * 1000);
        msg = 'Invalid OTP. Account locked due to 5 failed attempts. Please try again in 15 minutes.';
      } else {
        msg = `Invalid OTP code. Remaining attempts before lockout: ${5 - attempts}`;
      }

      await prisma.user.update({
        where: { id: user.id },
        data: { loginAttempts: attempts, lockUntil }
      });

      return res.status(401).json({ success: false, message: msg });
    }

    // OTP Verified successfully
    await prisma.user.update({
      where: { id: user.id },
      data: { otpCode: '', otpExpires: null, loginAttempts: 0, lockUntil: null }
    });

    const token = generateToken(user.id, user.role);
    user.password = undefined;

    res.status(200).json({ success: true, token, user });
  } catch (err) {
    res.status(400).json({ success: false, message: err.message });
  }
};

